from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

import gzip
import json
from collections import Counter

# Retain source records for illustrations whose original artwork code is unavailable.
# All inputs are committed logs; this script neither fetches the document nor calls models.
files = ("grader_baseline_initial.jsonl.gz", "grader_baseline_expansion.jsonl.gz", "grader_original.jsonl.gz")
chains = {}
rationales = {}
for filename in files:
    with gzip.open(ROOT / "original_data" / filename, "rt") as handle:
        for line_number, line in enumerate(handle, 1):
            if not line.strip():
                continue
            record = json.loads(line)
            if not (
                record.get("scenario") == "grader"
                and record.get("arm") == "baseline"
                and record.get("model_key") == "haiku"
                and record.get("N") == 30
            ):
                continue
            source = filename, line_number
            if record["spoke"] == "flip" and record["path"] == "adverse":
                key = record["run"], record["position"]
                assert key not in chains, key
                chains[key] = record, source
            if (
                record["spoke"] == "gov" and record["path"] == "normal"
                and (record["run"], record["position"]) in ((4, 10), (0, 15))
            ):
                key = record["run"], record["position"]
                assert key not in rationales, key
                rationales[key] = record, source

assert set(chains) == {(run, position) for run in range(40) for position in range(30)}
assert set(rationales) == {(4, 10), (0, 15)}
counts = []
for run in range(40):
    records = [chains[run, position][0] for position in range(30)]
    assert all(record["signal"] == "reads_transcript" for record in records[:4])
    counts.append(sum(record["signal"] == "output_only" for record in records))
majorities = Counter("correct" if count > 15 else "tied" if count == 15 else "wrong" for count in counts)
assert majorities == {"correct": 33, "tied": 4, "wrong": 3}, majorities

lines = [
    "# Raw-log sources for the blog illustrations",
    "",
    "Generated by `code/extract_blog_examples.py`. This file extracts the experimental "
    "content; it does not recreate the original artwork. See the "
    "[illustration map](../draft/illustrations/README.md) for exact image assets and hashes. "
    "Line numbers below count decompressed JSONL lines, starting at one. Worker IDs are "
    "zero-based: W00 is the first worker and W29 is the thirtieth.",
    "",
    "## Worker-0 prompt card",
    "",
]
worker_zero, source = chains[0, 0]
filename, line_number = source
lines += [
    f"Source: [{filename}](<../original_data/{filename}>), decompressed line {line_number}. "
    "Identifiers: `spoke=flip`, `scenario=grader`, `arm=baseline`, `path=adverse`, "
    "`model_key=haiku`, `N=30`, `run=0`, `position=0`. True state: `output_only`.",
    "",
    "### System message",
    "",
    "```text", worker_zero["system_prompt"], "```", "",
    "### User message",
    "",
    "```text", worker_zero["user_prompt"], "```", "",
    "The separate [three-way prompt comparison](../notes/grader-worker-0-prompts-three-way.md) "
    "adds the two incentive extensions. This illustration uses the original prompt.",
    "",
    "## Experiment overview: majority of private signals",
    "",
    f"Of the 40 original-grader adverse-start signal paths, {majorities['correct']} "
    f"have a strict majority of correct signals, {majorities['tied']} are tied, and "
    f"{majorities['wrong']} have a strict majority of wrong signals. The correct "
    "private signal is `output_only` (ACCEPTED); the wrong signal is "
    "`reads_transcript` (REJECTED). All 30 private signals count toward each majority, "
    "including the first four deliberately misleading signals. This is a signal tally, "
    "not the agents' consensus outcome.",
    "",
    "Sources: `grader_baseline_initial.jsonl.gz` (runs 0–9) and `grader_baseline_expansion.jsonl.gz` "
    "(runs 10–39), restricted to the identifiers above except `run` and `position`. "
    "Private signals match the paired no-board paths; board text is newly generated.",
    "",
    "| Run | Correct private signals / 30 | Private-signal majority |",
    "| --- | ---: | --- |",
]
for run, count in enumerate(counts):
    outcome = "Correct" if count > 15 else "Tie" if count == 15 else "Wrong"
    lines.append(f"| {run} | {count} | {outcome} |")

lines += [
    "", "## Two private-rationale excerpts", "",
    "These examples come from the original governance experiment's **normal** signal "
    "paths, not the 40 adverse-start replications plotted in the blog. The quoted text "
    "is `parsed.rationale`, which other workers could not see. Numerical assertions "
    "inside the rationales are the agents' own claims, not independently verified "
    "statistics. Full logged rationales follow so the displayed excerpts have context.", "",
]
for number, key in enumerate(((4, 10), (0, 15)), 1):
    record, (filename, line_number) = rationales[key]
    run, position = key
    interpretation = record["parsed"]["interpretation"]
    signal = record["signal"]
    outcome = "ACCEPTED" if signal == "output_only" else "REJECTED"
    correctness = "correct" if interpretation == "output_only" else "incorrect"
    lines += [
        f"### Excerpt {number}: run {run}, W{position:02d}", "",
        f"Source: [{filename}](<../original_data/{filename}>), decompressed line {line_number}. "
        "Identifiers: `spoke=gov`, `scenario=grader`, `arm=baseline`, `path=normal`, "
        f"`model_key=haiku`, `N=30`, `run={run}`, `position={position}`.", "",
        f"Private probe: **{outcome}** (`{signal}`). Private interpretation: "
        f"**{interpretation}** ({correctness}); confidence: {record['parsed']['confidence']}/100.", "",
        "```text", record["parsed"]["rationale"], "```", "",
    ]

animation = [chains[15, position][0] for position in range(30)]
accepted_at_w20 = sum(record["signal"] == "output_only" for record in animation[:21])
assert accepted_at_w20 == 13
lines += [
    "## Animated example: complete board for run 15", "",
    "Source: `grader_baseline_expansion.jsonl.gz`; identifiers `spoke=flip`, "
    "`scenario=grader`, `arm=baseline`, `path=adverse`, `model_key=haiku`, `N=30`, "
    "`run=15`. The GIF stops at W20; the full 30-worker board is retained below. "
    f"Through W20, the actual signals contain {accepted_at_w20} ACCEPTED and "
    f"{21 - accepted_at_w20} REJECTED outcomes. Agent claims and any tally mentioned "
    "in a post must be distinguished from those raw signals.", "",
    "Each entry shows the exact private-probe text in that worker's user message, "
    "the exact public `parsed.board_post`, and the separately recorded private "
    "interpretation. Private interpretations and confidence scores were not posted "
    "to the board by the experiment software.", "",
]
for position, record in enumerate(animation):
    filename, line_number = chains[15, position][1]
    probe = record["user_prompt"].split("PRIVATE PROBE RESULT (only you have seen this):\n", 1)[1].split("\n\nSHARED WORKER BOARD", 1)[0]
    assert "Result: " in probe
    lines += [
        f"### W{position:02d} (position {position + 1} of 30)", "",
        f"Decompressed source line {line_number}. Private signal: `{record['signal']}`. "
        f"Private interpretation: `{record['parsed']['interpretation']}`; "
        f"confidence: {record['parsed']['confidence']}/100.", "",
        "**Private probe (not visible to other workers)**", "",
        "```text", probe, "```", "",
        "**Public board post**", "",
        "```text", record["parsed"]["board_post"], "```", "",
    ]

output = ROOT / "modified_data/blog_illustration_sources.md"
output.parent.mkdir(parents=True, exist_ok=True)
output.write_text("\n".join(lines))
print(f"Wrote {output.relative_to(ROOT)}; 40 signal paths, 2 private rationales, 30 run-15 posts.")
